// 1st, 2nd, 3rd, 4th, 11th, 12th, 13th, 21st …
function ordinal(n: number) {
  const tens = n % 100
  if (tens >= 11 && tens <= 13) return `${n}th`
  return `${n}${["th", "st", "nd", "rd"][n % 10] ?? "th"}`
}
