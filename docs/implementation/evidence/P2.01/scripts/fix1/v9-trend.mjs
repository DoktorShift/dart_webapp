// Statistik after one finished game: the Verlauf group with its "—" and minimum, scrolled into view.
import { check, done, finishSeeded, nearWin, open, scrollAll, shot, tab, wait } from "./lib.mjs"
const { ctx, page } = await open({ seed: nearWin(["Anna", "Ben"]), viewport: { width: 390, height: 844 } })
await finishSeeded(page)
await page.getByRole("button", { name: "Deine Ergebnisse mitnehmen" }).click()
await wait(page, 900)
await page.getByRole("radio", { name: "Anna" }).click()
await page.getByRole("button", { name: "Profil anlegen" }).click()
await page.getByText("Dein Profil ist angelegt", { exact: false }).waitFor({ timeout: 30000 })
await page.getByRole("button", { name: "Fertig", exact: true }).click().catch(() => {})
await wait(page, 800)
await tab(page, "Profil")
await wait(page, 1500)
await page.getByRole("button", { name: "Statistik" }).click()
await wait(page, 1500)
await scrollAll(page)
await wait(page, 500)
await shot(page, "75-stats-trend-scrolled")
check("Verlauf shows '—' and 'Ab 15 Spielen.'", (await page.getByText("Ø der letzten 10 Spiele").count()) === 1 && (await page.getByText("Ab 15 Spielen.").count()) === 1)
await page.getByRole("radio", { name: "30 Tage" }).click().catch(() => page.getByRole("button", { name: "30 Tage" }).click())
await wait(page, 600)
await scrollAll(page)
await wait(page, 300)
await shot(page, "76-stats-trend-30days")
check("for a period, the row names the period before", (await page.getByText("Ø der 30 Tage davor").count()) === 1)
await ctx.close()
await done()
