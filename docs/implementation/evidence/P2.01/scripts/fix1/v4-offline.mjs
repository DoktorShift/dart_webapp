// Finding 5: relays down (one refused, one accepting TCP but never answering). Creating a profile
// finishes at once; the sheet stays until then; Bearbeiten works on the local version; Erweitert
// says what it knows. Run with nak :18971 stopped and blackhole.py holding :18972.
import { BASE, check, done, finishSeeded, nearWin, open, scrollAll, shot, tab, wait } from "./lib.mjs"

const { ctx, page, errors } = await open({ seed: nearWin(["Anna", "Ben"]), viewport: { width: 390, height: 844 } })
await finishSeeded(page)
await page.getByRole("button", { name: "Deine Ergebnisse mitnehmen" }).click()
await wait(page, 900)
await page.getByRole("radio", { name: "Anna" }).click()
const t0 = Date.now()
await page.getByRole("button", { name: "Profil anlegen" }).click()
await page.getByText("Dein Profil ist angelegt", { exact: false }).waitFor({ timeout: 60000 })
const took = Date.now() - t0
check("creating a profile does not wait for unreachable relays (< 3 s)", took < 3000, `${took} ms (lab value)`)
await shot(page, "41-create-offline-done")
await page.getByRole("button", { name: "Fertig", exact: true }).click().catch(() => {})
await wait(page, 800)
await tab(page, "Profil")
await wait(page, 2000)
await shot(page, "42-profile-offline")
check("the profile shows its name from this device while relays are down", (await page.locator('[data-tab-panel="profile"]').getByText("Anna").count()) >= 1)
// Bearbeiten: the local version is the base; nothing waits for relays.
await page.getByRole("button", { name: "Bearbeiten" }).click()
await wait(page, 1500)
await shot(page, "43-edit-offline")
await page.getByLabel("Anzeigename").fill("Anna S.")
const saveButton = page.getByRole("button", { name: "Speichern" })
check("Speichern is possible offline when the version is known here", (await saveButton.isEnabled()) === true)
const t1 = Date.now()
await saveButton.click()
await wait(page, 500)
await page.getByRole("button", { name: "Speichern" }).waitFor({ state: "detached", timeout: 15000 }).catch(() => {})
check("saving returns at once (< 3 s), the relays catch up by themselves", Date.now() - t1 < 3000, `${Date.now() - t1} ms (lab value)`)
await wait(page, 1500)
check("the new public name shows from this device", (await page.locator('[data-tab-panel="profile"]').getByText("Anna S.").count()) >= 1)
await scrollAll(page)
await wait(page, 400)
await page.getByRole("button", { name: "Erweitert" }).click()
await wait(page, 9000)
await shot(page, "44-advanced-offline")
check("Erweitert shows the list kept here with its relays' states, not 'loading'", (await page.getByText(/Nicht erreichbar|Langsam/).count()) >= 1 && (await page.getByText(/Deine Liste wird geladen/).count()) === 0)
console.log("errors", errors.join(" | ").slice(0, 300))
await ctx.close()
await done()
